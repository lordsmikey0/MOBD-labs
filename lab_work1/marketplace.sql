--
-- Лабораторная работа №1 - Проектирование и создание структуры базы данных
--

BEGIN;

DROP TABLE IF EXISTS deliveries, addresses, reviews, payments,
                     order_items, orders,
                     cart_items, carts,
                     stock, products,
                     categories, sellers, users
CASCADE;



CREATE TABLE public.users (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    full_name VARCHAR(128) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(30),
    role VARCHAR(30) NOT NULL DEFAULT 'customer',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT users_pkey PRIMARY KEY (id),

    CHECK (role IN ('customer', 'seller', 'admin'))
);


CREATE TABLE public.sellers (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    store_name VARCHAR(255) NOT NULL,
    description text,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	
	CONSTRAINT sellers_user_unique UNIQUE (user_id),
    CONSTRAINT sellers_pkey PRIMARY KEY (id),
    CONSTRAINT sellers_user_fkey FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE
);


CREATE TABLE public.categories (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    parent_id integer,
    name VARCHAR(100) NOT NULL,

    CONSTRAINT categories_pkey PRIMARY KEY (id),
    CONSTRAINT categories_parent_fkey FOREIGN KEY (parent_id)
        REFERENCES public.categories(id) ON DELETE SET NULL ON UPDATE CASCADE
);


CREATE TABLE public.products (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    seller_id integer NOT NULL,
    category_id integer NOT NULL,
    title VARCHAR(400) NOT NULL,
    description text,
    price numeric(12,2) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT products_pkey PRIMARY KEY (id),
    CONSTRAINT products_seller_fkey FOREIGN KEY (seller_id)
        REFERENCES public.sellers(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT products_category_fkey FOREIGN KEY (category_id)
        REFERENCES public.categories(id) ON DELETE RESTRICT ON UPDATE CASCADE,

    CHECK (price >= 0)
);


CREATE TABLE public.stock (
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 0,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT stock_pkey PRIMARY KEY (product_id),
    CONSTRAINT stock_product_fkey FOREIGN KEY (product_id)
        REFERENCES public.products(id) ON DELETE CASCADE ON UPDATE CASCADE,

    CHECK (quantity >= 0)
);


CREATE TABLE public.carts (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT carts_pkey PRIMARY KEY (id),
    CONSTRAINT carts_user_fkey FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE
);


CREATE TABLE public.cart_items (
    cart_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 1,

    CONSTRAINT cart_items_pkey PRIMARY KEY (cart_id, product_id),
    CONSTRAINT cart_items_cart_fkey FOREIGN KEY (cart_id)
        REFERENCES public.carts(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT cart_items_product_fkey FOREIGN KEY (product_id)
        REFERENCES public.products(id) ON DELETE CASCADE ON UPDATE CASCADE,

    CHECK (quantity > 0)
);


CREATE TABLE public.addresses (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    city VARCHAR(100),
    street VARCHAR(200),
    house VARCHAR(20),
    apartment VARCHAR(10),

    CONSTRAINT addresses_pkey PRIMARY KEY (id),
    CONSTRAINT addresses_user_fkey FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE
);


CREATE TABLE public.orders (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    status VARCHAR(40) NOT NULL DEFAULT 'pending',
    total_amount numeric(12,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT orders_pkey PRIMARY KEY (id),
    CONSTRAINT orders_user_fkey FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE RESTRICT ON UPDATE CASCADE,

    CHECK (total_amount >= 0),
    CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed'))
);


CREATE TABLE public.order_items (
    order_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL,
    unit_price numeric(12,2) NOT NULL,

    CONSTRAINT order_items_pkey PRIMARY KEY (order_id, product_id),
    CONSTRAINT order_items_order_fkey FOREIGN KEY (order_id)
        REFERENCES public.orders(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT order_items_product_fkey FOREIGN KEY (product_id)
        REFERENCES public.products(id) ON DELETE RESTRICT ON UPDATE CASCADE,

    CHECK (unit_price >= 0),
    CHECK (quantity > 0)
);


CREATE TABLE public.payments (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    order_id integer NOT NULL,
    amount numeric(12,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'pending',
    paid_at TIMESTAMPTZ,

    CONSTRAINT payments_pkey PRIMARY KEY (id),
    CONSTRAINT payments_order_fkey FOREIGN KEY (order_id)
        REFERENCES public.orders(id) ON DELETE RESTRICT ON UPDATE CASCADE,

    CHECK (amount >= 0),
    CHECK (status IN ('pending', 'paid', 'failed', 'refunded'))
);


CREATE TABLE public.deliveries (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    order_id integer NOT NULL,
    address_id integer NOT NULL,
    is_delivered boolean NOT NULL DEFAULT FALSE,
    delivery_status VARCHAR(30) NOT NULL DEFAULT 'pending',
    delivery_date TIMESTAMPTZ,

    CONSTRAINT deliveries_pkey PRIMARY KEY (id),
    CONSTRAINT deliveries_order_fkey FOREIGN KEY (order_id)
        REFERENCES public.orders(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT deliveries_address_fkey FOREIGN KEY (address_id)
        REFERENCES public.addresses(id) ON DELETE RESTRICT ON UPDATE CASCADE,

    CHECK (delivery_status IN ('pending', 'shipped', 'in_transit', 'delivered', 'cancelled'))
);


CREATE TABLE public.reviews (
    id integer GENERATED BY DEFAULT AS IDENTITY,
    user_id integer NOT NULL,
    product_id integer NOT NULL,
    score integer NOT NULL,
    comment text,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
	
	CONSTRAINT reviews_user_product_unique UNIQUE (user_id, product_id),
    CONSTRAINT reviews_pkey PRIMARY KEY (id),
    CONSTRAINT reviews_user_fkey FOREIGN KEY (user_id)
        REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE,
    CONSTRAINT reviews_product_fkey FOREIGN KEY (product_id)
        REFERENCES public.products(id) ON DELETE CASCADE ON UPDATE CASCADE,

    CHECK (score BETWEEN 1 AND 5)
);

--
-- Индексы внешних ключей
--

CREATE INDEX idx_products_seller_id ON public.products (seller_id);
CREATE INDEX idx_products_category_id ON public.products (category_id);
CREATE INDEX idx_categories_parent_id ON public.categories (parent_id);
CREATE INDEX idx_carts_user_id ON public.carts (user_id);
CREATE INDEX idx_addresses_user_id ON public.addresses (user_id);
CREATE INDEX idx_orders_user_id ON public.orders (user_id);
CREATE INDEX idx_order_items_product ON public.order_items (product_id);
CREATE INDEX idx_cart_items_product ON public.cart_items (product_id);
CREATE INDEX idx_payments_order_id ON public.payments (order_id);
CREATE INDEX idx_deliveries_order_id ON public.deliveries (order_id);
CREATE INDEX idx_deliveries_address_id ON public.deliveries (address_id);
CREATE INDEX idx_reviews_product_id ON public.reviews (product_id);
CREATE INDEX idx_reviews_user_id ON public.reviews (user_id);



COMMIT;
